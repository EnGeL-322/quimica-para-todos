import { tmpdir } from 'node:os'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { mkdirSync } from 'node:fs'
import { abrirApp, ESPERA, JS_AYUDAS } from './cdp.mjs'

const PERFIL = resolve(tmpdir(), 'reng-verificacion-d1b')
mkdirSync(fileURLToPath(new URL('../../docs/capturas-entrega-d', import.meta.url)), { recursive: true })
const fallos = []
const ok = (c, m) => {
  console.log(`${c ? 'OK ' : 'FALLO'} ${m}`)
  if (!c) fallos.push(m)
}
const app = await abrirApp(PERFIL)
const ir = async (sub, nivel = 'universitario') => {
  await app.ev(`localStorage.setItem('ciencia.nivel.simulador-quimica','${nivel}'); location.hash='#/simulador-quimica/${sub}'; location.reload()`)
  await ESPERA(2200)
  await app.ev(JS_AYUDAS)
}
const val = (etiqueta) => app.ev(`return [...document.querySelectorAll('.sim-res')].filter(e=>e.offsetParent).find(e=>e.textContent.includes(${JSON.stringify(etiqueta)}))?.querySelector('b')?.textContent ?? null`)
try {
  await app.ventana(1360, 860)

  console.log('--- Cinética')
  await ir('cinetica')
  let t = await app.ev(`return __q.texto('.q-tiempo ~ p, .q-tiempo + p')`)
  ok(/En pausa en t = 0/.test(t), `abre en pausa en t = 0 (${t})`)
  ok(await app.ev(`return !!__q.boton('Iniciar')`), 'botón «Iniciar»')
  ok((await val('[A] en este instante')) === '1 mol/L', `[A](0) = 1 mol/L (${await val('[A] en este instante')})`)
  const grafica = await app.ev(`return __q.visible('.grafica-xy svg').length`)
  ok(grafica >= 1, 'la gráfica se dibuja en el primer fotograma (no queda en blanco)')
  await app.ev(`__q.boton('Iniciar').click(); await __q.esperar(700)`)
  t = await app.ev(`return __q.texto('.q-tiempo ~ p, .q-tiempo + p')`)
  ok(/En marcha/.test(t), 'Iniciar pone en marcha')
  await app.ev(`__q.boton('Pausar').click(); await __q.esperar(200)`)
  const tPausa = await app.ev(`return __q.texto('.q-tiempo label span')`)
  await app.ev(`await __q.esperar(500)`)
  ok(tPausa === (await app.ev(`return __q.texto('.q-tiempo label span')`)), 'Pausar detiene el reloj')
  await app.ev(`__q.boton('Reiniciar').click(); await __q.esperar(200)`)
  ok(/t = 0/.test(await app.ev(`return __q.texto('.q-tiempo ~ p, .q-tiempo + p')`)), 'Reiniciar vuelve a t = 0')
  ok((await app.ev(`return __q.texto('.sim-campo span')`)).includes('mol/(L·s)') === false, 'orden 1 muestra k en 1/s')
  const unidadK = await app.ev(`return [...document.querySelectorAll('.sim-campo')].filter(c=>c.offsetParent).map(c=>c.textContent).join('|')`)
  ok(/k.*1\/s/.test(unidadK), `unidad de k orden 1: 1/s`)
  await app.ev(`const s=[...document.querySelectorAll('select')].filter(e=>e.offsetParent)[0]; Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype,'value').set.call(s,'0'); s.dispatchEvent(new Event('change',{bubbles:true})); await __q.esperar(200)`)
  ok(/mol\/\(L·s\)/.test(await app.ev(`return [...document.querySelectorAll('.sim-campo')].filter(c=>c.offsetParent).map(c=>c.textContent).join('|')`)), 'orden 0: k en mol/(L·s)')
  await app.ev(`const sl=document.querySelector('input[type=range][aria-label="Tiempo transcurrido"]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(sl, sl.max); sl.dispatchEvent(new Event('input',{bubbles:true})); await __q.esperar(300)`)
  t = await app.ev(`return __q.texto('.q-tiempo ~ p, .q-tiempo + p')`)
  ok(/\[A\] agotado/.test(t), `orden 0 al final del intervalo: «${t}»`)
  ok((await val('[A] en este instante')) === '0 mol/L', `[A] = 0 al final (${await val('[A] en este instante')})`)
  t = await app.ev(`return __q.texto('[data-diagnosticos="cinetica"]')`)
  console.log('diag cinética:', t.slice(0, 220))

  console.log('--- Equilibrio')
  await ir('equilibrio', 'quimico')
  await app.ev(`__q.boton('Calcular').click(); await __q.esperar(300)`)
  ok(/ya está en equilibrio|hacia los productos \(Q < K\)/.test(await app.ev(`return __q.texto('.q-salida')`)), 'Q frente a K con veredicto')
  ok((await val('Q inicial')) === '0' && (await val('K')) === '50', `Q = 0, K = 50 (${await val('Q inicial')}, ${await val('K')})`)
  await app.ev(`document.querySelectorAll('.panel-seccion summary').forEach(s=>{ if(s.textContent.includes('Perturbación')) s.click() }); await __q.esperar(150)`)
  await app.ev(`const s=[...document.querySelectorAll('select')].filter(e=>e.offsetParent).find(e=>e.closest('label')?.textContent.includes('Añadir (o quitar)')); Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype,'value').set.call(s,'0'); s.dispatchEvent(new Event('change',{bubbles:true}));`)
  await app.ev(`__q.escribir(__q.campo('Cantidad (negativa = quitar)'),'-5'); await __q.esperar(100); __q.boton('Actualizar').click(); await __q.esperar(300)`)
  t = await app.ev(`return __q.texto('.q-salida')`)
  ok(/No se calculó la perturbación/.test(t) && /solo hay/.test(t) && /Q inicial/.test(t), 'quitar de más: error en la perturbación y el estado inicial sigue visible')
  console.log('   ', t.slice(t.indexOf('No se calculó'), t.indexOf('No se calculó') + 260))
  await app.ev(`__q.escribir(__q.campo('H₂ inicial'),'0'); __q.escribir(__q.campo('I₂ inicial'),'0'); __q.escribir(__q.campo('HI inicial'),'0.4'); __q.escribir(__q.campo('Cantidad (negativa = quitar)'),'0.1'); await __q.esperar(100); __q.boton('Actualizar').click(); await __q.esperar(300)`)
  t = await app.ev(`return __q.texto('.q-salida')`)
  ok(/Falta H₂, I₂ \(reactivo\)/.test(t) && /Q → ∞/.test(t), 'sin reactivos pero con producto: se nombra qué falta y evoluciona hacia reactivos')
  await app.ev(`__q.escribir(__q.campo('HI inicial'),'0'); await __q.esperar(100); __q.boton('Actualizar').click(); await __q.esperar(300)`)
  t = await app.ev(`return __q.texto('.q-salida')`)
  ok(/No se puede concluir/.test(t) && /Sistema vacío/.test(t) && /H₂, I₂, HI/.test(t), 'sistema vacío: «No se puede concluir» con las especies')
  console.log('   ', t.slice(0, 260))

  console.log('--- Energía')
  await ir('termo', 'cientifico')
  await app.ev(`__q.boton('Calcular').click(); await __q.esperar(300)`)
  t = await app.ev(`return __q.texto('.q-salida')`)
  ok(/Calor de reacción: ΔH°/.test(t) && /Condición: 298,15 K/.test(t), 'ΔH° con su condición')
  ok(/Favorable no significa rápida/.test(t), 'favorable ≠ rápido visible')
  ok(/usa ΔH° a 298,15 K aunque|ΔH° a 298,15 K aunque pidas otra temperatura/.test(t), 'aclara que ΔH° no cambia con T')
  await app.ev(`__q.escribir(__q.campo('Temperatura'),'1'); await __q.esperar(100); __q.boton('Actualizar').click(); await __q.esperar(300)`)
  t = await app.ev(`return __q.texto('.q-salida')`)
  ok(/fuera del rango numérico/.test(t) && /ln K/.test(t), 'T = 1 K: K fuera de rango, no se muestra ∞')
  ok(!/∞/.test(await val('Constante de equilibrio K') ?? ''), 'K no se presenta como ∞')
  ok(/Extrapolación|extrapolan/.test(t), 'avisa de la extrapolación')
  await app.ev(`__q.escribir(__q.campo('Temperatura'),'298.15'); await __q.esperar(100); const sel=[...document.querySelectorAll('select')].filter(e=>e.offsetParent)[0]; Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype,'value').set.call(sel,'etanol'); sel.dispatchEvent(new Event('change',{bubbles:true})); await __q.esperar(100); __q.boton('Actualizar').click(); await __q.esperar(300)`)
  t = await app.ev(`return __q.texto('.q-salida')`)
  ok(/Falta la entropía estándar/.test(t) && /No hay S° para C₂H₅OH/.test(t), 'etanol: no se inventa ΔG')

  console.log('--- Mezcla y guardado con cambios pendientes')
  await ir('mezcla')
  await app.ev(`__q.boton('Calcular').click(); await __q.esperar(400)`)
  t = await app.ev(`return __q.texto('.q-salida')`)
  ok(/Antes de la equivalencia: sobra ácido/.test(t), 'región de la valoración: sobra ácido')
  ok(/Carga: cumplido/.test(t), 'balance de carga verificado en pantalla')
  await app.ev(`__q.escribir(__q.campo('Volumen de disolución básica añadido'),'30'); await __q.esperar(200)`)
  ok(/Resultado del cálculo anterior/.test(await app.ev(`return __q.texto('.q-salida')`)), 'cambios sin calcular → resultado marcado como anterior')
  await app.ev(`__q.boton('Guardar en cuaderno').click(); await __q.esperar(600)`)
  t = await app.ev(`return __q.texto('[data-guardar-pendiente]')`)
  ok(/se guardará el cálculo aplicado/.test(t) && /12,5 mL/.test(t), `aviso de qué se guardará (${t.slice(0, 160)})`)
  await app.ev(`[...document.querySelectorAll('button')].find(b=>b.offsetParent&&b.textContent.trim()==='Cancelar').click()`)
  await app.ev(`__q.boton('Actualizar').click(); await __q.esperar(400)`)
  t = await app.ev(`return __q.texto('.q-salida')`)
  ok(/Después de la equivalencia: sobra base/.test(t), 'tras Actualizar: después de la equivalencia, sobra base')

  console.log('consola:', app.consola.slice(0, 5))
  ok(app.consola.length === 0, 'consola sin errores')
} finally {
  await app.cerrar()
}
