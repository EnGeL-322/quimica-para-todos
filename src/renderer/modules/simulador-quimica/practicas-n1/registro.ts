const rengTituloSubtema = (rengId: string): string => {
  for (const rengN of RENG_TEMARIO_GENERADO.niveles) for (const rengB of rengN.bloques) for (const rengS of rengB.subtemas) if (rengS.id === rengId) return rengS.titulo
  throw new Error(`Subtema inexistente en el temario: ${rengId}`)
}

export function rengGrupoN1(rengSubtema: string, rengPracticas: readonly RengPracticaN1[]): RengGrupoPracticasN1 {
  const rengLeccion = rengLeccionN1DeSubtema(rengSubtema)
  if (!rengLeccion) throw new Error(`No hay lección por capas para el subtema ${rengSubtema}`)
  if (rengPracticas.some((rengP) => rengP.subtema !== rengSubtema)) throw new Error(`Hay prácticas de otro subtema en el grupo ${rengSubtema}`)
  return { subtema: rengSubtema, leccion: rengLeccion.id, bloque: rengLeccion.bloque, posicion: rengLeccion.posicion, titulo: rengTituloSubtema(rengSubtema), practicas: rengPracticas }
}

